[CmdletBinding()]param([Parameter(Mandatory)][string]$ProfileRoot)
Set-StrictMode -Version 2
$ErrorActionPreference='Stop'
$env:PSModulePath=$PSHOME+'\Modules;'+$env:SystemRoot+'\System32\WindowsPowerShell\v1.0\Modules'
Add-Type -AssemblyName System.Windows.Forms
Add-Type -AssemblyName System.Drawing
$root=[IO.Path]::GetFullPath($ProfileRoot).TrimEnd('\','/')
$script:process=$null;$script:operation='';$script:folder='';$script:nonce='';$script:version=''
$form=[Windows.Forms.Form]::new();$form.Text='Habumi updates';$form.AutoScaleMode='Dpi'
$form.ClientSize=[Drawing.Size]::new(490,248);$form.FormBorderStyle='FixedDialog';$form.MaximizeBox=$false
$form.Font=[Drawing.Font]::new('Segoe UI',10);$form.StartPosition='CenterScreen'
$label=[Windows.Forms.Label]::new();$label.SetBounds(16,16,458,42)
try{$installed=([IO.File]::ReadAllText((Join-Path $root 'release-profile.json'))|ConvertFrom-Json).Version}catch{$installed='unknown'}
$label.Text="Installed: $installed`nUpdates run only when you request them. Android data is preserved."
$preview=[Windows.Forms.CheckBox]::new();$preview.SetBounds(16,64,440,26);$preview.Text='Include experimental prereleases';$preview.Checked=$installed.Contains('-')
$message=[Windows.Forms.Label]::new();$message.SetBounds(16,100,458,64);$message.Text='Check for an update, or restore the previous software version.'
$buttons=@{}
$names=@('Check','Install','Rollback','Recover')
for($i=0;$i -lt $names.Count;$i++){
    $button=[Windows.Forms.Button]::new();$button.SetBounds(16+$i*116,184,108,32);$button.Text=$names[$i]
    $button.Tag=$names[$i];$buttons[$names[$i]]=$button;$form.Controls.Add($button)
}
$buttons.Install.Enabled=$false
$form.Controls.AddRange(@($label,$preview,$message))
function Set-Buttons([bool]$Enabled){
    foreach($button in $buttons.Values){$button.Enabled=$Enabled}
    $preview.Enabled=$Enabled
    $buttons.Install.Enabled=$Enabled -and [bool]$script:version
}
function Start-Operation([string]$Operation){
    if($script:process){return}
    if($Operation -ne 'Check'){
        if([Windows.Forms.MessageBox]::Show("$Operation Habumi software? Android must be closed. Your data and configuration will be preserved.",'Habumi updates','YesNo','Question','Button2') -ne 'Yes'){return}
    }
    $script:nonce=[guid]::NewGuid().ToString('N')
    $script:folder=Join-Path ([IO.Path]::GetTempPath()) ('Habumi-update-'+$script:nonce)
    [IO.Directory]::CreateDirectory($script:folder)|Out-Null
    foreach($name in @('Update-Worker.ps1','Profile-Update.psm1','Profile-Data.psm1','Profile-SystemInfo.ps1','Profile-Growth.ps1')){
        [IO.File]::Copy((Join-Path $PSScriptRoot $name),(Join-Path $script:folder $name),$false)
    }
    $request=@{Schema='habumi.update-ui.v1';Nonce=$script:nonce;ProfileRoot=$root;Operation=$Operation;Prerelease=$preview.Checked;ExpectedVersion=$script:version}
    $requestPath=Join-Path $script:folder 'request.json'
    [IO.File]::WriteAllText($requestPath,($request|ConvertTo-Json),[Text.UTF8Encoding]::new($false))
    $start=[Diagnostics.ProcessStartInfo]::new();$start.FileName=Join-Path $env:SystemRoot 'System32/WindowsPowerShell/v1.0/powershell.exe'
    $worker=Join-Path $script:folder 'Update-Worker.ps1'
    # Paths are generated by Windows and contain no quotation marks.
    $start.Arguments='-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "'+$worker+'" -RequestPath "'+$requestPath+'"'
    $start.WorkingDirectory=$script:folder;$start.UseShellExecute=$false;$start.CreateNoWindow=$true
    $script:process=[Diagnostics.Process]::Start($start);$script:operation=$Operation
    Set-Buttons $false;$message.Text="$Operation in progress. Keep this window open."
}
foreach($button in $buttons.Values){$button.Add_Click({try{Start-Operation ([string]$this.Tag)}catch{$message.Text=$_.Exception.Message;Set-Buttons $true}})}
$timer=[Windows.Forms.Timer]::new();$timer.Interval=300
$timer.Add_Tick({
    if(-not $script:process -or -not $script:process.HasExited){return}
    $code=$script:process.ExitCode;$script:process.Dispose();$script:process=$null
    try{
        $result=[IO.File]::ReadAllText((Join-Path $script:folder 'result.json'))|ConvertFrom-Json
        if($result.Nonce -cne $script:nonce){throw 'Updater result identity does not match.'}
        $message.Text=$result.Message
        if($code -ne 0 -or -not $result.OK){$script:version=''}
        elseif($script:operation -eq 'Check'){
            $script:version=[string]$result.Release.Version
            if($script:version -ceq $installed){$message.Text="Version $installed is already installed.";$script:version=''}
        }else{
            $script:version='';$message.Text+="`nClose this window and start Habumi from its normal shortcut."
        }
    }catch{$message.Text="No verified completion result. Operation folder: $script:folder";$script:version=''}
    Set-Buttons $true
})
$form.Add_FormClosing({if($script:process){$_.Cancel=$true;$message.Text='Wait for the current operation to finish. Its recovery files will be retained.'}})
$timer.Start();[void]$form.ShowDialog();$timer.Stop();$timer.Dispose();$form.Dispose()
